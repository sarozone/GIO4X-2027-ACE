/** filed without brackets or a leading article: the first letter of the name */
const letterOf = (name: string) => name.charAt(0).toUpperCase();

export const COMMODITIES: readonly Commodity[] = entries
  .map((e) => ({ ...e, letter: letterOf(e.name) }))
  .sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));

const bySlug = new Map(COMMODITIES.map((c) => [c.slug, c]));
export const getCommodity = (slug: string) => bySlug.get(slug);
export const commodityHref = (c: Pick<Commodity, "slug">) => `/markets/commodities/${c.slug}`;

/** The GIO4X instrument for a commodity, or undefined: read from instruments.ts, so the two cannot disagree. */
export function commodityInstrument(c: Commodity): Instrument | undefined {
  if (!c.gio4x) return undefined;
  const [cls, slug] = c.gio4x.split("/");
  return getInstrument(cls, slug);
}

/** The commodities GIO4X lists as instruments. */
export const TRADED_COMMODITIES: readonly Commodity[] = COMMODITIES.filter((c) => commodityInstrument(c));

/** The first sentence of an entry: the line shown in lists, search results and page descriptions. */
export const commodityLine = (c: Commodity) => {
  const stop = c.is.indexOf(". ");
  return stop === -1 ? c.is : c.is.slice(0, stop + 1);
};

